struct EngineReply {
    let ok: Bool
    let object: [String: Any]
    let output: String
    let diagnostics: String
    let exitCode: Int32

    var error: [String: Any] { object["error"] as? [String: Any] ?? [:] }
    var code: String { error["code"] as? String ?? "ENGINE_RESPONSE" }
    var message: String { error["message"] as? String ?? "未能读取安装器的结果。请复制诊断信息，保留给维护者排查。" }
    func string(_ key: String) -> String? { object[key] as? String ?? error[key] as? String }

    static func failure(_ code: String, _ message: String, details: String = "") -> EngineReply {
        EngineReply(ok: false, object: ["ok": false, "error": ["code": code, "message": message]],
                    output: "", diagnostics: details.isEmpty ? message : details, exitCode: -1)
    }

    static func decode(stdout: String, stderr: String, processExit: Int32, elevated: Bool) -> EngineReply {
        var payload = stdout.trimmingCharacters(in: .whitespacesAndNewlines)
        var engineExit = processExit
        let diagnostics = "进程退出码：\(processExit)\n标准输出：\n\(stdout)\n标准错误：\n\(stderr)"
        if elevated {
            if processExit != 0 {
                // A standard macOS password dialog cancellation is not an engine failure.
                if stderr.contains("(-128)") || stderr.contains("error number -128") {
                    return .failure("AUTH_CANCELLED", "已取消管理员授权。没有继续本次操作。", details: diagnostics)
                }
                return .failure("AUTH_FAILED", "管理员授权未完成。请稍后重试，或请这台 Mac 的管理员协助。", details: diagnostics)
            }
            guard let marker = payload.range(of: engineExitMarker, options: .backwards),
                  let code = Int32(payload[marker.upperBound...].trimmingCharacters(in: .whitespacesAndNewlines)) else {
                return .failure("ENGINE_RESPONSE", "未收到完整的安装结果。请保留诊断信息和已有备份。", details: diagnostics)
            }
            engineExit = code
            payload = String(payload[..<marker.lowerBound]).trimmingCharacters(in: .whitespacesAndNewlines)
        }
        guard let data = payload.data(using: .utf8),
              let parsed = try? JSONSerialization.jsonObject(with: data),
              let object = parsed as? [String: Any],
              let reportedOK = object["ok"] as? Bool else {
            return .failure("ENGINE_RESPONSE", "安装器没有返回有效结果。请复制诊断信息，保留给维护者排查。", details: diagnostics)
        }
        if reportedOK && engineExit != 0 {
            return .failure("ENGINE_EXIT", "安装进程未正常结束，暂不能确认操作完成。请保留诊断信息和已有备份。", details: diagnostics)
        }
        return EngineReply(ok: reportedOK && engineExit == 0, object: object, output: payload,
                           diagnostics: diagnostics, exitCode: engineExit)
    }
}

enum ArgumentEscaping {
    static func shell(_ value: String) -> String {
        "'" + value.replacingOccurrences(of: "'", with: "'\\''") + "'"
    }
    static func appleScript(_ value: String) -> String {
        "\"" + value.replacingOccurrences(of: "\\", with: "\\\\")
            .replacingOccurrences(of: "\"", with: "\\\"")
            .replacingOccurrences(of: "\r", with: "\\r")
            .replacingOccurrences(of: "\n", with: "\\n")
            .replacingOccurrences(of: "\t", with: "\\t") + "\""
    }
    static func privilegedScript(executable: String, arguments: [String]) -> String {
        let invocation = ([executable] + arguments).map(shell).joined(separator: " ")
        // Preserve JSON on nonzero engine exit: osascript otherwise discards it.
        // The exit marker is generated by fixed shell text, never user input.
        let command = invocation + "; patch_exit=$?; /usr/bin/printf '\\n" + engineExitMarker + "%s\\n' \"$patch_exit\"; exit 0"
        return "do shell script " + appleScript(command) + " with administrator privileges"
    }
}

private final class DataCapture: @unchecked Sendable {
    private let lock = NSLock()
    private var stored = Data()
    func set(_ data: Data) { lock.lock(); stored = data; lock.unlock() }
    func string() -> String { lock.lock(); defer { lock.unlock() }; return String(decoding: stored, as: UTF8.self) }
}

private struct ProcessOutput {
    let stdout: String
    let stderr: String
    let exitCode: Int32
}

private func executeProcess(_ executable: URL, arguments: [String], environment: [String: String]) throws -> ProcessOutput {
    let process = Process()
    process.executableURL = executable
    process.arguments = arguments
    process.environment = environment
    let out = Pipe(), err = Pipe()
    process.standardOutput = out
    process.standardError = err
    process.standardInput = FileHandle.nullDevice
    try process.run()
    let captures = DispatchGroup()
    let output = DataCapture(), errors = DataCapture()
    // Drain both pipes concurrently, including output larger than a pipe buffer.
    captures.enter()
    DispatchQueue.global(qos: .userInitiated).async {
        output.set(out.fileHandleForReading.readDataToEndOfFile()); captures.leave()
    }
    captures.enter()
    DispatchQueue.global(qos: .userInitiated).async {
        errors.set(err.fileHandleForReading.readDataToEndOfFile()); captures.leave()
    }
    process.waitUntilExit()
    captures.wait()
    return ProcessOutput(stdout: output.string(), stderr: errors.string(), exitCode: process.terminationStatus)
}

final class EngineRunner {
    let preview: Bool
    init(preview: Bool) { self.preview = preview }

    func run(_ command: String, app: String, state: String? = nil, elevated: Bool = false,
             completion: @escaping (EngineReply) -> Void) {
        // Preview cannot spawn an engine, even for a nominally read-only command.
        guard !preview else {
            completion(.failure("PREVIEW_ONLY", "这是界面预览，所有安装、检查和恢复操作均已停用。")); return
        }
        guard ["preflight", "install", "verify", "restore"].contains(command),
              app.hasPrefix("/"), !app.contains("\0"), !(state?.contains("\0") ?? false) else {
            completion(.failure("INVALID_ARGUMENTS", "应用或备份路径无效。请重新选择。")); return
        }
        guard let resources = Bundle.main.resourceURL else {
            completion(.failure("ENGINE_MISSING", "安装器文件不完整，请重新下载完整的安装器。")); return
        }
        let executable = resources.appendingPathComponent("backend/patch-engine")
        guard FileManager.default.isExecutableFile(atPath: executable.path) else {
            completion(.failure("ENGINE_MISSING", "安装器缺少内置组件，请重新下载完整的安装器。")); return
        }
        var arguments = [command, "--app", app]
        if let state = state {
            arguments += ["--state", state]
        } else {
            let backupRoot = elevated ? privilegedBackupRoot : FileManager.default.homeDirectoryForCurrentUser
                .appendingPathComponent("Library/Application Support/ScreenStudioChinesePatch/backups").path
            arguments += ["--backup-dir", backupRoot]
        }
        if command == "install" { arguments += ["--accept-signature-change"] }

        let installerBundle = Bundle.main.bundleURL
        DispatchQueue.global(qos: .userInitiated).async {
            // Do not forward caller-controlled Python/import or dynamic loader variables.
            let environment = ["PATH": "/usr/bin:/bin:/usr/sbin:/sbin", "LANG": "en_US.UTF-8",
                               "HOME": FileManager.default.homeDirectoryForCurrentUser.path]
            do {
                if elevated {
                    // An ad-hoc signature checks bundle integrity, not publisher identity.
                    // The backend independently validates the privileged path contract.
                    let signature = try executeProcess(URL(fileURLWithPath: "/usr/bin/codesign"),
                        arguments: ["--verify", "--deep", "--strict", installerBundle.path], environment: environment)
                    guard installerBundle.pathExtension == "app", signature.exitCode == 0 else {
                        DispatchQueue.main.async {
                            completion(.failure("INSTALLER_SIGNATURE", "安装器完整性检查未通过，已停止管理员授权。请重新下载完整安装器。",
                                                details: "安装器：\(installerBundle.path)\n\(signature.stdout)\n\(signature.stderr)"))
                        }
                        return
                    }
                }
                let result = try executeProcess(elevated ? URL(fileURLWithPath: "/usr/bin/osascript") : executable,
                    arguments: elevated ? ["-e", ArgumentEscaping.privilegedScript(executable: executable.path, arguments: arguments)] : arguments,
                    environment: environment)
                let reply = EngineReply.decode(stdout: result.stdout, stderr: result.stderr,
                                               processExit: result.exitCode, elevated: elevated)
                DispatchQueue.main.async { completion(reply) }
            } catch {
                DispatchQueue.main.async {
                    completion(.failure("ENGINE_START", "未能启动内置安装组件。请复制诊断信息。", details: error.localizedDescription))
                }
                return
            }
        }
    }
}

private struct InstallationReceipt: Codable {
    let app: String
    let state: String
    let backup: String
    let elevated: Bool
    var status: String

    static func from(_ reply: EngineReply, app: String, elevated: Bool) -> InstallationReceipt? {
        guard let state = reply.string("state"), state.hasPrefix("/") else { return nil }
        let backup = reply.string("backup") ?? reply.string("original_backup")
            ?? URL(fileURLWithPath: state).deletingLastPathComponent().appendingPathComponent("original.app").path
        return InstallationReceipt(app: app, state: state, backup: backup, elevated: elevated,
                                   status: reply.string("status") ?? "needs_review")
    }
}

private enum FriendlyFailure {
    static func content(_ reply: EngineReply) -> (String, String) {
        switch reply.code {
        case "APP_RUNNING":
            return ("请先退出 Screen Studio", "请保存正在编辑的内容，在 Screen Studio 菜单中选择“退出 Screen Studio”，然后点击“重试”。安装器不会替你强制关闭应用。")
        case "AUTH_CANCELLED":
            return ("已取消授权", "管理员授权已取消，没有继续本次操作。准备好后可以重试。")
        case "WRITE_PERMISSION":
            return ("需要管理员授权", "当前账户没有写入应用所在文件夹的权限。你可以通过 macOS 的密码窗口授权后重试。")
        case "VERSION_MISMATCH", "ARCHITECTURE_MISMATCH", "BUNDLE_ID_MISMATCH", "WRONG_APP", "ORIGINAL_HASH_MISMATCH":
            return ("这个版本暂不支持", "此补丁只支持原版 Screen Studio 4.1.0-5005（Apple Silicon），且文件必须完全匹配。请选择对应版本；不要覆盖更新后的应用。")
        case "DISK_SPACE":
            return ("可用空间不足", "安装需要为完整原版备份、临时副本和回滚预留空间。请清理磁盘后重试。")
        case "INVALID_APP", "APP_NOT_FOUND":
            return ("请重新选择应用", "没有找到可用的 Screen Studio 应用。点击“选择应用…”并选择 Screen Studio.app。")
        case "STATE_NOT_FOUND", "STATE_REQUIRED", "INVALID_STATE", "STATE_APP_MISMATCH", "BACKUP_MISMATCH":
            return ("需要检查原版备份", "安装记录或备份未通过检查。请保留现有文件并复制诊断信息，不要反复安装或移动备份。")
        case "APP_CHANGED", "INSTALLED_HASH_MISMATCH", "RESTORE_HASH_MISMATCH":
            return ("应用文件已经变化", "当前应用与安装记录不再匹配，操作已停止。请保留备份和诊断信息，不要用旧备份强行覆盖更新后的应用。")
        case "COMMAND_FAILED" where (reply.error["command"] as? String) == "/usr/bin/codesign"
            || (reply.error["command"] as? [String])?.first == "/usr/bin/codesign":
            return ("应用签名不匹配", "所选应用没有通过签名检查。安装只支持文件完整、未修改过的官方匹配版本。请保留当前文件，并复制诊断信息。")
        case "ENGINE_MISSING", "ENGINE_START", "ENGINE_RESPONSE", "ENGINE_EXIT", "PREVIEW_ONLY", "AUTH_FAILED", "INSTALLER_SIGNATURE":
            return ("暂未完成操作", reply.message)
        default:
            return ("暂未完成操作", "检查或安装未完成。请保留现有应用、备份和诊断信息，不要反复安装。你可以复制诊断信息交给维护者排查。")
        }
    }
}

private final class PrimaryActionButton: NSButton {
    override func draw(_ dirtyRect: NSRect) {
        let purple = NSColor(calibratedRed: 0.43, green: 0.32, blue: 0.73, alpha: 1)
        let fill = isEnabled ? (isHighlighted ? purple.blended(withFraction: 0.12, of: .black)! : purple)
            : NSColor(calibratedWhite: 0.83, alpha: 1)
        fill.setFill()
        NSBezierPath(roundedRect: bounds.insetBy(dx: 1, dy: 1), xRadius: 9, yRadius: 9).fill()
        let paragraph = NSMutableParagraphStyle()
        paragraph.alignment = .center
        let attributes: [NSAttributedString.Key: Any] = [
            .font: font ?? NSFont.systemFont(ofSize: 14, weight: .semibold),
            .foregroundColor: isEnabled ? NSColor.white : NSColor.darkGray,
            .paragraphStyle: paragraph
        ]
        let height = (title as NSString).size(withAttributes: attributes).height
        (title as NSString).draw(in: NSRect(x: 8, y: (bounds.height - height) / 2, width: bounds.width - 16, height: height),
                                withAttributes: attributes)
    }
}


        guard let receipt = receipt else { return false }
        return !["restored", "already_restored", "original_verified"].contains(receipt.status)
    }

    private func updateControls() {
        let displayAsReady = !preview || renderPath != nil
        pathLabel.stringValue = appPath
        pathLabel.toolTip = appPath
        chooseButton.isEnabled = !busy && displayAsReady
        installButton.isEnabled = !busy && displayAsReady
        restoreButton.isEnabled = !busy && displayAsReady
        backupButton.isEnabled = !busy && receipt != nil
        backupButton.isHidden = receipt == nil
        openButton.isEnabled = !busy && currentVerified && !preview
        openButton.isHidden = !currentVerified
        detailsButton.isEnabled = !lastDetails.isEmpty
        detailsButton.isHidden = lastDetails.isEmpty
        permissionsButton.isEnabled = !busy && displayAsReady
        if busy {
            spinner.startAnimation(nil)
        } else {
            spinner.stopAnimation(nil)
            installButton.title = retryOperation != nil ? "重试" : receiptNeedsVerification ? "检查安装状态" : "检查并安装"
        }
    }

    private func status(_ title: String, _ body: String) {
        stateTitle.stringValue = title
        stateBody.stringValue = body
        NSAccessibility.post(element: stateBody, notification: .valueChanged)
    }

    private func begin(_ title: String, _ body: String) {
        busy = true
        retryOperation = nil
        status(title, body)
        updateControls()
    }

    private func save(_ newReceipt: InstallationReceipt) {
        receipts[newReceipt.app] = newReceipt
        if !preview, let data = try? JSONEncoder().encode(receipts) { UserDefaults.standard.set(data, forKey: "installationReceipts") }
    }

    private func record(_ reply: EngineReply, app: String, elevated: Bool, command: String) {
        lastDetails = "\(applicationTitle)\n操作：\(command)\n应用：\(app)\n管理员授权：\(elevated ? "是" : "否")\n\n\(reply.diagnostics)"
        if let newReceipt = InstallationReceipt.from(reply, app: app, elevated: elevated) { save(newReceipt) }
    }

    private func failed(_ reply: EngineReply, retry: (() -> Void)? = nil) {
        busy = false
        currentVerified = false
        let content = FriendlyFailure.content(reply)
        status(content.0, content.1)
        // A failed mutation may have retained staging/rollback data. Only simple
        // stopped-before-work cases receive a retry; all other cases retain diagnostics.
        if ["APP_RUNNING", "AUTH_CANCELLED", "AUTH_FAILED", "WRITE_PERMISSION", "DISK_SPACE", "ENGINE_START"].contains(reply.code) {
            retryOperation = retry
        }
        updateControls()
    }

    @objc private func chooseApp() {
        guard !busy else { return }
        let dialog = NSOpenPanel()
        dialog.title = "选择 Screen Studio 应用"
        dialog.message = "请选择要安装补丁的 Screen Studio.app。"
        dialog.prompt = "选择此应用"
        dialog.canChooseDirectories = false
        dialog.canChooseFiles = true
        dialog.treatsFilePackagesAsDirectories = false
        dialog.allowsMultipleSelection = false
        dialog.allowedContentTypes = [.applicationBundle]
        dialog.directoryURL = URL(fileURLWithPath: "/Applications")
        dialog.beginSheetModal(for: window) { [weak self] response in
            guard let self = self, response == .OK, let selected = dialog.url else { return }
            self.appPath = selected.standardizedFileURL.path
            self.currentVerified = false
            self.retryOperation = nil
            self.status("已选择应用", "安装前会检查版本、官方签名与文件是否匹配。请先保存工作并退出所选应用。")
            self.updateControls()
        }
    }

    @objc private func installOrVerify() {
        guard !busy && !preview else { return }
        if let retry = retryOperation { retryOperation = nil; retry(); return }
        if let receipt = receipt, receiptNeedsVerification {
            verifyExisting(receipt); return
        }
        begin("正在检查应用…", "正在核对版本、签名、文件与可用空间。这一步不会修改 Screen Studio。")
        let selected = appPath
        runner.run("preflight", app: selected) { [weak self] reply in
            guard let self = self else { return }
            self.record(reply, app: selected, elevated: false, command: "preflight")
            if reply.ok { self.install(app: selected, elevated: false) }
            else if reply.code == "WRITE_PERMISSION" { self.offerAdministrator(app: selected) }
            else { self.failed(reply, retry: { [weak self] in self?.installOrVerify() }) }
        }
    }

    private func offerAdministrator(app: String) {
        let alert = NSAlert()
        alert.messageText = "需要管理员授权才能安装"
        alert.informativeText = "当前账户无法写入应用文件夹。继续后，macOS 会弹出管理员密码窗口；安装器不会收集密码。原版备份将保存在这台 Mac 的系统资料库中，恢复时也需要管理员授权。"
        alert.addButton(withTitle: "授权并安装")
        alert.addButton(withTitle: "取消")
        alert.beginSheetModal(for: window) { [weak self] response in
            guard let self = self else { return }
            if response == .alertFirstButtonReturn { self.install(app: app, elevated: true) }
            else { self.failed(.failure("AUTH_CANCELLED", "已取消管理员授权。"), retry: { [weak self] in self?.installOrVerify() }) }
        }
    }

    private func install(app: String, elevated: Bool) {
        begin(elevated ? "等待授权并安装…" : "正在备份并安装…", "安装器会先完整备份，再构建和校验中文副本。请保持窗口开启；可能需要几分钟。")
        runner.run("install", app: app, elevated: elevated) { [weak self] reply in
            guard let self = self else { return }
            self.record(reply, app: app, elevated: elevated, command: "install")
            guard reply.ok else {
                self.failed(reply, retry: { [weak self] in self?.installOrVerify() }); return
            }
            guard let receipt = InstallationReceipt.from(reply, app: app, elevated: elevated) else {
                self.failed(.failure("ENGINE_RESPONSE", "安装器未返回恢复记录。请保留诊断信息与备份，暂不要重复安装。")); return
            }
            self.verifyExisting(receipt, afterInstall: true)
        }
    }

    private func verifyExisting(_ receipt: InstallationReceipt, afterInstall: Bool = false) {
        begin("正在校验安装文件…", "正在使用本次安装记录校验应用与原版备份。管理员安装可能再次显示 macOS 授权窗口。")
        runner.run("verify", app: receipt.app, state: receipt.state, elevated: receipt.elevated) { [weak self] reply in
            guard let self = self else { return }
            self.record(reply, app: receipt.app, elevated: receipt.elevated, command: "verify")
            guard reply.ok else {
                self.failed(reply, retry: { [weak self] in self?.verifyExisting(receipt, afterInstall: afterInstall) }); return
            }
            self.busy = false
            self.retryOperation = nil
            self.currentVerified = reply.string("status") == "localized_verified"
            if self.currentVerified {
                self.status(afterInstall ? "中文补丁已安装，文件校验通过" : "中文补丁文件校验通过",
                            "现在可以打开 Screen Studio。若提示权限，请按“权限设置帮助”重新授权。实际录屏、声音和导出仍需你在应用中检查。")
            } else {
                self.status("当前为原版应用", "原版文件校验通过。如需重新安装中文补丁，请点击“检查并安装”。")
            }
            self.updateControls()
        }
    }

    @objc private func restoreOriginal() {
        guard !busy && !preview else { return }
        if let receipt = receipt { confirmRestore(receipt); return }
        let dialog = NSOpenPanel()
        dialog.title = "选择原版恢复记录"
        dialog.message = "选择安装时保存的 state.json。恢复前会核对该记录对应的应用与备份。"
        dialog.prompt = "读取恢复记录"
        dialog.allowedContentTypes = [.json]
        dialog.allowsMultipleSelection = false
        dialog.directoryURL = FileManager.default.homeDirectoryForCurrentUser.appendingPathComponent("Library/Application Support/ScreenStudioChinesePatch/backups")
        dialog.beginSheetModal(for: window) { [weak self] response in
            guard let self = self, response == .OK, let file = dialog.url else { return }
            guard let data = try? Data(contentsOf: file),
                  let object = (try? JSONSerialization.jsonObject(with: data)) as? [String: Any],
                  let target = object["app_path"] as? String, target.hasPrefix("/"), target.hasSuffix(".app"),
                  let backup = object["backup_app"] as? String, backup.hasPrefix("/") else {
                self.failed(.failure("INVALID_STATE", "无法读取此恢复记录。")); return
            }
            let elevated = file.standardizedFileURL.path.hasPrefix(privilegedBackupRoot + "/")
            let imported = InstallationReceipt(app: target, state: file.standardizedFileURL.path, backup: backup,
                                               elevated: elevated, status: object["phase"] as? String ?? "needs_review")
            self.confirmRestore(imported)
        }
    }

    private func confirmRestore(_ receipt: InstallationReceipt) {
        let alert = NSAlert()
        alert.messageText = "恢复这份 Screen Studio 的原版？"
        alert.informativeText = "请先保存工作并退出 Screen Studio。恢复会核对原版备份，保留替换前的副本；应用若已更新，安装器将停止。\n\n目标应用：\n\(receipt.app)\n\n恢复记录：\n\(receipt.state)" + (receipt.elevated ? "\n\n此备份需要管理员授权。" : "")
        alert.addButton(withTitle: "恢复原版")
        alert.addButton(withTitle: "取消")
        alert.beginSheetModal(for: window) { [weak self] response in
            guard let self = self, response == .alertFirstButtonReturn else { return }
            self.performRestore(receipt)
        }
    }

    private func performRestore(_ receipt: InstallationReceipt) {
        guard !preview else { return }
        appPath = receipt.app
        save(receipt)
        begin("正在恢复原版…", "正在核对备份并恢复本次安装前的应用。请保持窗口开启；不会替你关闭正在运行的 Screen Studio。")
        runner.run("restore", app: receipt.app, state: receipt.state, elevated: receipt.elevated) { [weak self] reply in
            guard let self = self else { return }
            self.record(reply, app: receipt.app, elevated: receipt.elevated, command: "restore")
            guard reply.ok else {
                self.failed(reply, retry: { [weak self] in self?.performRestore(receipt) }); return
            }
            self.busy = false
            self.currentVerified = false
            self.retryOperation = nil
            self.status("已恢复原版", "原版已恢复并通过文件校验。备份仍然保留。重新打开 Screen Studio 后，请检查权限与原有功能。")
            self.updateControls()
        }
    }


private func runSelfTests() -> Int32 {
    var failures: [String] = []
    var assertions = 0
    func expect(_ condition: Bool, _ name: String) { assertions += 1; if !condition { failures.append(name) } }
    let success = EngineReply.decode(stdout: "{\"ok\":true,\"status\":\"localized_verified\",\"state\":\"/tmp/test/state.json\"}", stderr: "", processExit: 0, elevated: false)
    expect(success.ok && success.string("status") == "localized_verified", "decode success")
    expect(!EngineReply.decode(stdout: "{\"ok\":true}", stderr: "", processExit: 2, elevated: false).ok, "reject nonzero success")
    let failure = EngineReply.decode(stdout: "{\"ok\":false,\"error\":{\"code\":\"APP_RUNNING\",\"message\":\"请退出\",\"state\":\"/backup/state.json\"}}", stderr: "", processExit: 1, elevated: false)
    expect(!failure.ok && failure.code == "APP_RUNNING" && failure.string("state") == "/backup/state.json", "decode failure and recovery state")
    expect(!EngineReply.decode(stdout: "not JSON", stderr: "", processExit: 0, elevated: false).ok, "reject malformed response")
    expect(!EngineReply.decode(stdout: "{}", stderr: "", processExit: 0, elevated: false).ok, "reject missing ok")
    let elevated = EngineReply.decode(stdout: "{\"ok\":true}\r\n" + engineExitMarker + "0\n", stderr: "", processExit: 0, elevated: true)
    expect(elevated.ok, "decode elevated success")
    let elevatedFailure = EngineReply.decode(stdout: "{\"ok\":false,\"error\":{\"code\":\"DISK_SPACE\",\"message\":\"不足\"}}\n" + engineExitMarker + "1\n", stderr: "", processExit: 0, elevated: true)
    expect(!elevatedFailure.ok && elevatedFailure.code == "DISK_SPACE", "retain privileged JSON failure")
    expect(!EngineReply.decode(stdout: "{\"ok\":true}", stderr: "", processExit: 0, elevated: true).ok, "require privileged exit marker")
    expect(!EngineReply.decode(stdout: "{\"ok\":true}\n" + engineExitMarker + "1", stderr: "", processExit: 0, elevated: true).ok, "require privileged engine success")
    let cancelled = EngineReply.decode(stdout: "", stderr: "execution error: User canceled. (-128)", processExit: 1, elevated: true)
    expect(cancelled.code == "AUTH_CANCELLED", "recognize cancelled password")
    expect(ArgumentEscaping.shell("a'b") == "'a'\\''b'", "quote apostrophe")
    expect(ArgumentEscaping.shell("$(id);`whoami`\n") == "'$(id);`whoami`\n'", "quote shell metacharacters")
    expect(ArgumentEscaping.appleScript("\"\\\n\r\t") == "\"\\\"\\\\\\n\\r\\t\"", "quote AppleScript string")
    let script = ArgumentEscaping.privilegedScript(executable: "/Applications/a'b.app/engine", arguments: ["install", "--app", "/test/$(id).app"])
    expect(script.hasPrefix("do shell script \"") && script.hasSuffix(" with administrator privileges"), "fixed authorization statement")
    expect(script.contains("patch_exit=$?") && script.contains(engineExitMarker), "privileged result protocol")
    expect(InstallationReceipt.from(success, app: "/Applications/Test.app", elevated: false)?.backup == "/tmp/test/original.app", "receipt backup fallback")
    expect(FriendlyFailure.content(failure).0 == "请先退出 Screen Studio", "running-app instruction")
    var previewCalled = false
    EngineRunner(preview: true).run("install", app: "/must/not/be/touched.app") { reply in
        previewCalled = true
        expect(reply.code == "PREVIEW_ONLY", "preview refuses engine")
    }
    expect(previewCalled, "preview never starts asynchronous process")
    if failures.isEmpty { print("PASS: \(assertions) GUI helper checks; no UI opened, no engine launched, no files modified."); return 0 }
    for failure in failures { fputs("FAIL: \(failure)\n", stderr) }
    return 1
}

if CommandLine.arguments.contains("--self-test") {
    exit(runSelfTests())
} else {
    let renderIndex = CommandLine.arguments.firstIndex(of: "--render-preview")
    if let index = renderIndex, index + 1 >= CommandLine.arguments.count {
        fputs("Usage: --render-preview /absolute/output.png\n", stderr); exit(2)
    }
    let renderPath = renderIndex.map { CommandLine.arguments[$0 + 1] }
    if let path = renderPath, !path.hasPrefix("/") {
        fputs("Preview PNG path must be absolute.\n", stderr); exit(2)
    }
    let preview = CommandLine.arguments.contains("--preview") || renderPath != nil
    let application = NSApplication.shared
    let delegate = InstallerDelegate(preview: preview, renderPath: renderPath)
    application.setActivationPolicy(renderPath == nil ? .regular : .prohibited)
    application.delegate = delegate
    withExtendedLifetime(delegate) { application.run() }
}

        let candidates = ["/Applications/Screen Studio.app",
                          FileManager.default.homeDirectoryForCurrentUser.appendingPathComponent("Applications/Screen Studio.app").path]
        appPath = candidates.first(where: { FileManager.default.fileExists(atPath: $0) }) ?? candidates[0]
        if renderPath == nil { buildMenu() }
        buildWindow()
        updateControls()
        if let renderPath = renderPath {
            renderPreview(to: renderPath)
            return
        }
        window.center()
        window.makeKeyAndOrderFront(nil)
        NSApp.activate(ignoringOtherApps: true)
    }

    private func renderPreview(to path: String) {
        guard preview, let content = window.contentView else { exit(2) }
        content.layoutSubtreeIfNeeded()
        guard let bitmap = content.bitmapImageRepForCachingDisplay(in: content.bounds) else {
            fputs("Cannot allocate preview bitmap.\n", stderr); exit(2)
        }
        window.effectiveAppearance.performAsCurrentDrawingAppearance {
            content.cacheDisplay(in: content.bounds, to: bitmap)
        }
        guard let png = bitmap.representation(using: .png, properties: [:]) else {
            fputs("Cannot encode preview PNG.\n", stderr); exit(2)
        }
        do {
            try png.write(to: URL(fileURLWithPath: path), options: .atomic)
            print("Rendered initial UI preview: \(path). No visible window or engine operation.")
            NSApp.terminate(nil)
        } catch {
            fputs("Cannot write preview PNG: \(error.localizedDescription)\n", stderr); exit(2)
        }
    }

